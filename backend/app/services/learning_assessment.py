def exam(topic, form):
    selected = BANK[topic][2 * form:2 * form + 2]
    rows = []
    for index, (question, *choices) in enumerate(selected):
        rotate = (form + index + 1) % 3
        rows.append({"id": str(index + 1), "question": question,
                     "choices": choices[rotate:] + choices[:rotate], "correct": str((3 - rotate) % 3)})
    return rows

